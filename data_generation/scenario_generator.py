def bank_profile(bank_id="BANK_01"):
    """Return the profile for one of the three supported banks."""
    for profile in BANK_PROFILES:
        if profile.bank_id == bank_id:
            return profile
    known = ", ".join(profile.bank_id for profile in BANK_PROFILES)
    raise ValueError(f"Unknown bank_id {bank_id!r}. Choose one of: {known}.")


def scenario_for_number(transaction_number):
    """Return the scenario that owns this transaction number."""
    matches = [
        scenario
        for scenario in SCENARIOS
        if scenario.start_number <= transaction_number <= scenario.end_number
    ]
    if len(matches) != 1:
        raise ValueError(
            f"Transaction {transaction_number} must belong to exactly one scenario."
        )
    return matches[0]


def account_role(account_number):
    """Return the simulated role for an account number from 1 to 100."""
    if 1 <= account_number <= 60:
        return "CUSTOMER"
    if account_number in (61, 62, 63, 64, 65):
        return "MERCHANT"
    if account_number == 66:
        return "MARKETPLACE"
    if account_number == 67:
        return "VENDOR"
    if account_number in (68, 71, 72, 75):
        return "COLLECTOR"
    if account_number in (69, 70):
        return "EMPLOYER"
    if account_number == 73:
        return "UTILITY"
    if account_number == 74:
        return "CORPORATE"
    if 76 <= account_number <= 85:
        return "MULE_CHAIN"
    if 86 <= account_number <= 92:
        return "DORMANT_MULE"
    if 93 <= account_number <= 100:
        return "SMURF_HUB"
    raise ValueError(f"Account number {account_number} is outside 1..{ACCOUNT_COUNT}.")
